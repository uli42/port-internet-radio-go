import os

def generate():
    output = []
    output.append("package main\n")
    output.append("// Code generated by generate_assets.py; DO NOT EDIT.\n")
    output.append("var embeddedAssets = map[string][]byte{")

    plugins_dir = "plugins"
    for root, dirs, files in os.walk(plugins_dir):
        for file in files:
            if file.endswith(".png"):
                full_path = os.path.join(root, file)
                # Keep the URL path representation, e.g. "/plugins/TuneIn/html/images/icon.png"
                url_path = "/" + full_path.replace("\\", "/")
                
                with open(full_path, "rb") as f:
                    content = f.read()
                
                byte_strs = [f"0x{b:02x}" for b in content]
                # Format bytes nicely in chunks
                formatted_bytes = []
                for i in range(0, len(byte_strs), 16):
                    formatted_bytes.append("\t\t" + ", ".join(byte_strs[i:i+16]) + ",")
                
                output.append(f'\t"{url_path}": []byte{{\n' + "\n".join(formatted_bytes) + "\n\t},")

    output.append("}\n")

    with open("assets.go", "w") as f:
        f.write("\n".join(output))
    print("assets.go generated successfully!")

if __name__ == "__main__":
    generate()
